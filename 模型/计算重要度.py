# -*- coding: utf-8 -*-
# ============================================================
# 文件：计算重要度.py
# 作用：实现白皮书"步骤 3：计算参数重要性评分"。
#       用【Fisher 信息】衡量每个参数对这个分类任务有多重要：
#         1. 拿一小批校准数据（如 60 条），逐条前向 + 反向。
#         2. 把每个参数的梯度平方累加起来（梯度平方大 = 这个参数稍微动一下，
#            输出就变化大 = 对任务重要）。
#         3. 得到一张和模型参数"形状完全一样"的重要性评分表。
#       这张表是后面"选哪些参数进补丁"的依据。
#
# 数学说明（给懂的人看）：Fisher 信息 ≈ E[ (∂logP(y|x)/∂θ)² ]，
# 这里用"校准集上的梯度平方平均"来估计。
#
# 需要的条件：
#   - 依赖 torch。
#   - 需要一块足够显存的显卡（重要度表用 fp32 保存，2B 模型约占用 8GB 显存，
#     和模型本身加在一起需要 16GB 以上；如果报显存不够，请调小批次或换大显存环境）。
# ============================================================

import torch                          # 深度学习框架


def 计算Fisher重要度(配置, 模型, 校准数据加载器, 类别token编号: torch.Tensor) -> dict:
    """计算每个参数对任务的重要性评分。

    参数：
      配置             ：配置项对象（含 Fisher校准条数）。
      模型             ：基座模型 A（要在微调前、在原始模型上算）。
      校准数据加载器    ：由校准数据包成的 DataLoader（每批取几条）。
      类别token编号     ：类别词 token 编号。
    返回：
      重要度字典 {参数名: 与参数同形状的 fp32 张量}。
      值越大表示该参数对任务越关键。
    """
    # 1) 准备工作：模型切到评估模式（关掉 dropout，保证打分稳定），并允许计算梯度
    模型.eval()
    设备 = next(模型.parameters()).device
    # 用"梯度平方和"做重要度估计，fp32 累加避免精度丢失
    重要度 = {
        名字: torch.zeros_like(参数, dtype=torch.float32, device=设备)
        for 名字, 参数 in 模型.named_parameters()
    }
    # 交叉熵损失（和训练用的完全一致，保证口径统一）
    损失函数 = torch.nn.CrossEntropyLoss()
    已用样本数 = 0
    批次上限 = 配置.Fisher校准条数  # 最多用多少条校准数据

    print(f"开始计算 Fisher 重要度（校准数据上限 {批次上限} 条）...")
    # 2) 逐批处理校准数据
    for 批次 in 校准数据加载器:
        # 超过上限就停
        if 已用样本数 >= 批次上限:
            break
        输入编号 = 批次["输入编号"].to(设备)
        注意力掩码 = 批次["注意力掩码"].to(设备)
        标签编号 = 批次["标签编号"].to(设备)
        # 前向 + 反向（这一步必须开梯度，才能拿到每个参数的梯度）
        with torch.enable_grad():
            输出 = 模型(input_ids=输入编号, attention_mask=注意力掩码)
            logits = 输出.logits if hasattr(输出, "logits") else 输出[0]
            类别得分 = logits[:, -1, 类别token编号]
            损失 = 损失函数(类别得分, 标签编号)
        损失.backward()
        # 3) 把每个参数的梯度平方累加到重要度表里
        for 名字, 参数 in 模型.named_parameters():
            if 参数.grad is not None:
                重要度[名字] += (参数.grad.detach().float() ** 2)
        # 4) 清空梯度，准备下一条
        模型.zero_grad(set_to_none=True)
        已用样本数 += 输入编号.size(0)
        if 配置.是否显示详细日志:
            print(f"  Fisher 进度：已用 {已用样本数} 条校准数据")

    # 5) 取平均：除以实际用掉的样本数
    实际样本数 = max(已用样本数, 1)
    for 名字 in 重要度:
        重要度[名字] /= 实际样本数
    print(f"Fisher 重要度计算完成，共评估 {实际样本数} 条样本。")
    return 重要度
