def 检查Python环境() -> list:
    """检查 Python 版本是否满足要求，返回一批检查结果（列表）。

    返回值说明：每一条结果是一个字典，格式为
    {"项目": 检查项名字, "状态": "通过"/"警告"/"错误", "说明": 详细描述}。
    这样统一结构，方便最后统一打印。
    """
    结果列表 = []
    # 读取当前 Python 主版本号和次版本号，例如 3.10.12 → (3, 10)
    当前主版本, 当前次版本 = sys.version_info[0], sys.version_info[1]
    # 记录检查结果：Qwen3.5 与主流库要求 Python 3.8 以上，太老会有兼容问题
    结果列表.append({
        "项目": "Python 版本",
        "状态": "通过" if (当前主版本, 当前次版本) >= (3, 8) else "警告",
        "说明": f"当前 Python {sys.version.split()[0]}（要求 >=3.8）",
    })
    # 记录操作系统信息，方便排查问题
    结果列表.append({
        "项目": "操作系统",
        "状态": "通过",
        "说明": f"{platform.system()} {platform.release()}",
    })
    return 结果列表


def 检查显卡() -> list:
    """检查有没有可用的 NVIDIA 显卡、显存多大。

    说明：PyTorch 只在真正用到时才会初始化 CUDA，所以这里用 torch 检查是安全的。
    如果没显卡，实验会退化为 CPU 计算，会非常慢（但不报错）。
    """
    结果列表 = []
    try:
        import torch   # 延迟导入 torch（本地没装 torch 时也不影响其它检查项）
        # 判断 CUDA 是否可用
        if torch.cuda.is_available():
            # 拿显卡数量
            显卡数 = torch.cuda.device_count()
            # 拿第一块显卡的名字和显存（单位是字节，除以 1024^3 转成 GB）
            显卡名 = torch.cuda.get_device_name(0)
            显存GB = torch.cuda.get_device_properties(0).total_memory / (1024 ** 3)
            结果列表.append({
                "项目": "显卡",
                "状态": "通过",
                "说明": f"检测到 {显卡数} 块显卡：{显卡名}，显存约 {显存GB:.1f} GB",
            })
            # 提示：2B 模型全参数微调建议显存 >= 16GB；不足会跑不动或很吃力
            if 显存GB < 16:
                结果列表.append({
                    "项目": "显存容量",
                    "状态": "警告",
                    "说明": f"显存仅 {显存GB:.1f} GB，2B 全参数微调可能紧张，建议把【批次大小】调小到 1~2",
                })
        else:
            # 没有 CUDA 显卡：torch 可能是 CPU 版，或确实没有 GPU。
            # 本实验要全参数微调 2B 模型，CPU 上不可行，必须标"错误"让用户换 GPU 实例。
            结果列表.append({
                "项目": "显卡",
                "状态": "错误",
                "说明": ("没有检测到 CUDA 显卡（可能是 CPU 版 torch，或当前是 CPU 实例）。"
                         "本实验要在 2B 模型上做全参数微调，CPU 不可行。"
                         "请到魔搭【新建 Notebook】并选择【GPU 免费实例】（如 A10 24G），"
                         "再到该实例里重新拉取本仓库运行。"),
            })
    except Exception as 异常:
        结果列表.append({
            "项目": "显卡",
            "状态": "错误",
            "说明": f"检查显卡时出错：{异常}",
        })
    return 结果列表


def 检查关键库() -> list:
    """检查 4 个关键库是否安装、版本是否满足要求。

    特别强调：Qwen3.5 系列（qwen3_5 架构）要求 transformers 版本 >=5.3.0。
    """
    结果列表 = []
    # 每个库：名字、要求的最低版本
    # 注意：torch 要求 >=2.5.0 是因为 transformers 5.x 硬性要求；
    #       且本实验要全参数微调 2B 模型，必须是 GPU 版 torch。
    库清单 = [
        ("torch", "2.5.0", "深度学习框架，必须>=2.5.0（transformers 5.x 要求），且要 GPU 版"),
        ("transformers", "5.3.0", "加载/微调模型，必须>=5.3.0 才能支持 Qwen3.5（qwen3_5 架构）"),
        ("modelscope", "1.18.0", "从魔搭下载模型，必须"),
        ("peft", "0.13.0", "跑 LoRA 对比基线用，可缺但会跳过 LoRA 实验"),
        ("datasets", "2.19.0", "数据集处理，可选"),
    ]
    # 逐个检查
    for 库名, 最低版本, 用途 in 库清单:
        try:
            # 动态导入该库
            import importlib
            模块 = importlib.import_module(库名)
            版本号 = getattr(模块, "__version__", "未知")
            # 简单版本比较：把版本号拆成数字再逐段比
            def 版本号转数字(版本字符串):
                """把 '5.2.0' 变成 (5,2,0) 这种可比较的元组，非数字段当 0 处理。"""
                import re
                return tuple(int(段) for 段 in re.findall(r"\d+", 版本字符串)[:3]) or (0,)
            if 版本号转数字(版本号) >= 版本号转数字(最低版本):
                结果列表.append({
                    "项目": f"{库名}",
                    "状态": "通过",
                    "说明": f"已安装 {版本号}（{用途}）",
                })
            else:
                # 版本太旧：torch 版本不够会直接被 transformers 禁用（报"PyTorch was not found"），所以标"错误"
                状态 = "错误" if 库名 == "torch" else "警告"
                结果列表.append({
                    "项目": f"{库名}",
                    "状态": 状态,
                    "说明": f"已安装 {版本号}，但要求 >= {最低版本}，请执行：pip install -r requirements.txt",
                })
        except ImportError:
            # 库没装：看它是不是必须的，必须的标错误，可选的标警告
            状态 = "错误" if 库名 in ("torch", "transformers", "modelscope") else "警告"
            # torch 缺失是最常见问题，给出针对性安装提示
            if 库名 == "torch":
                安装提示 = ("未安装。请先执行：pip install torch --index-url "
                            "https://download.pytorch.org/whl/cu124 ，装完重启内核；"
                            "再执行：pip install -r requirements.txt")
            else:
                安装提示 = "请执行：pip install -r requirements.txt"
            结果列表.append({
                "项目": f"{库名}",
                "状态": 状态,
                "说明": f"未安装（{用途}）。{安装提示}",
            })
    return 结果列表


def 检查模型缓存() -> list:
    """检查目标模型是否已经下载到本地缓存。

    说明：第一次运行会花几分钟从魔搭下载模型（约 4.5GB），
    下载完会存到【缓存/模型】目录，以后就不用再下了。
    """
    结果列表 = []
    模型目录 = 配置.模型缓存目录 / 配置.模型ID.split("/")[-1]
    # 判断缓存目录里是否已经存在模型文件（用有没有 safetensors 文件来粗略判断）
    是否已缓存 = 模型目录.exists() and any(模型目录.glob("*.safetensors"))
    if 是否已缓存:
        结果列表.append({
            "项目": "模型缓存",
            "状态": "通过",
            "说明": f"模型已下载到：{模型目录}",
        })
    else:
        结果列表.append({
            "项目": "模型缓存",
            "状态": "信息",
            "说明": f"模型还未下载（{配置.模型ID}，约 4.5GB）。运行时将自动从魔搭下载到：{模型目录}",
        })
    return 结果列表


def 汇总打印(所有结果: list) -> bool:
    """把全部检查结果统一打印出来，并返回"是否全部通过"。

    参数：所有结果 是所有检查函数返回的结果拼接成的列表。
    返回值：True 表示全部通过，False 表示有问题需要处理。
    """
    print("=" * 60)
    print("【环境自检报告】")
    print("=" * 60)
    是否全部通过 = True   # 先假设全部通过，遇到 错误 就翻转为 False
    # 按状态排序：错误/警告排前面，方便一眼看到问题
    for 单条 in 所有结果:
        if 单条["状态"] == "错误":
            是否全部通过 = False
        # 用不同符号标记不同状态：✔ 通过 / ! 警告 / ✘ 错误 / · 信息
        符号 = {"通过": "✔", "警告": "!", "错误": "✘", "信息": "·"}.get(单条["状态"], "·")
        print(f"  [{符号}] {单条['项目']}：{单条['说明']}")
    print("=" * 60)
    # 给出总结论和建议
    if 是否全部通过:
        print("结论：环境基本就绪，可以开始实验。")
    else:
        print("结论：存在【错误】项，请先按上面的提示安装/处理，再重新运行。")
    print("提示：如果 transformers 版本不对，请执行：pip install -r requirements.txt")
    return 是否全部通过


def 运行自检() -> bool:
    """环境自检的总入口：依次执行所有检查项，汇总结果。

    这个函数既可以被【主入口.py】调用，也可以单独运行：
        python 工具/环境自检.py
    """
    全部结果 = []                        # 收集所有检查结果
    全部结果 += 检查Python环境()          # 第 1 步：检查 Python
    全部结果 += 检查关键库()              # 第 2 步：检查关键库
    全部结果 += 检查显卡()                # 第 3 步：检查显卡
    全部结果 += 检查模型缓存()            # 第 4 步：检查模型缓存
    return 汇总打印(全部结果)             # 统一打印并返回是否通过


