# ---------- 导入标准库 ----------
import sys                          # 系统相关
from pathlib import Path            # 路径工具

# ---------- 第一步：把项目根目录加入模块搜索路径 ----------
# 这样无论在哪个目录运行，都能正确找到 配置/模型/数据 等子包。
项目根 = Path(__file__).resolve().parent.parent
if str(项目根) not in sys.path:
    sys.path.insert(0, str(项目根))


def 主函数():
    """程序主流程：自检 → 读配置 → 跑实验。"""
    # 1) 环境自检（缺库/缺显卡会有明确提示）
    print("第一步：环境自检 ...")
    from 工具.环境自检 import 运行自检
    自检通过 = 运行自检()
    if not 自检通过:
        print("\n⚠️ 自检发现错误项。如果缺少关键库，请先执行：pip install -r requirements.txt")
        # 即使有错误也继续尝试（有的库缺失只是跳过对应功能），让报错信息更具体
    # 2) 读配置
    from 配置.配置 import 配置
    # 3) 跑完整实验
    from 实验.实验总控 import 运行完整实验
    运行完整实验(配置)
    # 4) 完成提示
    print("\n🎉 实验全部完成！请查看 结果/报告.md 获取对比结论。")


# ---------- 程序入口 ----------
# 只有直接运行本文件时才执行，被 import 时不执行。
if __name__ == "__main__":
    主函数()
