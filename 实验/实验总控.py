# -*- coding: utf-8 -*-
# ============================================================
# 文件：实验总控.py
# 作用：整个实验的【总指挥】，按正确顺序把所有步骤串起来：
#   ┌─ 1. 加载基座模型 A 与分词器
#   ├─ 2. 构建任务数据（训练/测试/校准）
#   ├─ 3. 评估基座 A 的准确率（对照基准，通常≈随机）
#   ├─ 4. 在 A 上计算 Fisher 重要度（谁对任务重要）
#   ├─ 5. 保存基座 A 的完整权重（供补丁应用/重置用）
#   ├─ 6. 全参数微调 A → 专家 B，评估 B
#   ├─ 7. 生成各种策略/比例的硬核补丁（只存被选位置的差值）
#   ├─ 8. 逐个补丁"盖"回基座并评估，同时测切换耗时
#   ├─ 9. 训练 LoRA 对照组并评估
#   └─ 10. 汇总生成报告
#
# 显存管理要点（不细看也行，知道"为什么要这样排"即可）：
#   - Fisher 重要度表很占显存，算完立刻搬到 CPU 再释放；
#   - 全量微调很占显存，微调完拿完专家参数就释放模型；
#   - 评估补丁时只保留一份模型，每评估一个补丁就"重置→覆盖"。
#
# 需要的条件：
#   - 所有下层模块（模型/数据/补丁/评估）依赖齐全。
#   - 建议在有显卡的 modelscope notebook 上运行。
# ============================================================

# ---------- 导入标准库 ----------
import gc                                    # 垃圾回收
import torch                                 # 深度学习框架

# ---------- 导入本项目各模块 ----------
from 配置.配置 import 配置项                    # 配置类型（用于类型标注）
from 数据.数据接口 import 构建数据, 验证类别词是单个Token
from 模型.模型加载 import 加载模型和分词器
from 模型.模型工具 import (
    构建数据加载器, 统计参数总数, 保存状态到磁盘, 从磁盘读状态, 释放模型, 拿类别token编号,
)
from 模型.计算重要度 import 计算Fisher重要度
from 模型.微调 import 分类训练器, 训练LoRA模型
from 补丁.生成补丁 import 生成补丁文件
from 补丁.应用补丁 import 重置模型为基座, 应用补丁到模型, 计时专家切换
from 评估.评估 import 评估分类准确率
from 实验.汇总报告 import 生成报告


# ---------- 冒烟模式：把规模缩小 ----------
def 应用冒烟设置(配置: 配置项):
    """冒烟模式 = 快速验证流程能否跑通，把所有规模缩到最小。

    只影响本次运行，不改配置文件。正式实验把配置里的【冒烟模式】设回 False。
    """
    if not 配置.冒烟模式:
        return
    print("⚠️ 冒烟模式已开启：规模已大幅缩小，仅用于验证整套流程能跑通，结果无统计意义。")
    配置.每类训练条数 = 40          # 每类训练样本 40 条
    配置.每类测试条数 = 30          # 每类测试样本 30 条
    配置.每类校准条数 = 8           # 每类校准样本 8 条
    配置.Fisher校准条数 = 20        # Fisher 用 20 条
    配置.训练轮数 = 1               # 只训 1 轮
    配置.最大训练步数 = 40          # 最多 40 步
    配置.是否跑LoRA基线 = False     # 跳过 LoRA（太慢）
    配置.补丁清单 = ({"名称": "策略A_2%", "策略": "策略A", "比例": 0.02},)  # 只测一个补丁


# ---------- 主流程 ----------
def 运行完整实验(配置: 配置项) -> dict:
    """执行整个钻石架构验证实验，返回包含全部结果的字典。

    参数：配置 配置项对象。
    返回：记录 字典（准确率、补丁结果、LoRA 结果等），供报告使用。
    """
    # 0) 冒烟模式调整（可选）
    应用冒烟设置(配置)
    # 记录实验数据的总账本
    记录 = {"补丁结果": [], "LoRA结果": []}

    # ============================================================
    # 步骤 1：加载基座模型 A 与分词器
    # ============================================================
    print("\n" + "=" * 60)
    print("步骤 1/10：加载基座模型")
    print("=" * 60)
    模型, 分词器 = 加载模型和分词器(配置)
    记录["模型参数总数"] = 统计参数总数(模型)

    # ============================================================
    # 步骤 2：构建任务数据
    # ============================================================
    print("\n" + "=" * 60)
    print("步骤 2/10：构建任务数据")
    print("=" * 60)
    训练集, 测试集, 校准集, 类别到编号 = 构建数据(配置, 分词器)
    # 校验类别词都是"单个 token"（我们的分类原理要求这一点）
    验证类别词是单个Token(分词器, 配置.任务类别)
    # 类别词转 token 编号
    类别token编号 = 拿类别token编号(分词器, 类别到编号, next(模型.parameters()).device)
    # 构建三个 DataLoader：训练(打乱)、测试(不打乱)、校准(不打乱)
    训练加载器 = 构建数据加载器(配置, 训练集, 是否打乱=True)
    测试加载器 = 构建数据加载器(配置, 测试集, 是否打乱=False)
    校准加载器 = 构建数据加载器(配置, 校准集, 是否打乱=False)
    print(f"训练集 {len(训练集)} 条，测试集 {len(测试集)} 条，校准集 {len(校准集)} 条")

    # ============================================================
    # 步骤 3：评估基座 A（对照基准）
    # ============================================================
    print("\n" + "=" * 60)
    print("步骤 3/10：评估基座模型 A（预期≈随机）")
    print("=" * 60)
    基座准确率 = 评估分类准确率(配置, 模型, 测试加载器, 类别token编号)
    print(f"基座 A 准确率：{基座准确率:.1%}")
    记录["基座准确率"] = 基座准确率

    # ============================================================
    # 步骤 4：计算 Fisher 重要度（在基座 A 上）
    # ============================================================
    print("\n" + "=" * 60)
    print("步骤 4/10：计算 Fisher 参数重要度")
    print("=" * 60)
    重要度 = 计算Fisher重要度(配置, 模型, 校准加载器, 类别token编号)
    # 立刻搬到 CPU 并释放显存（重要度表 fp32 很大，别占着显卡）
    print("正在把重要度表搬到内存（CPU）以释放显存 ...")
    重要度 = {名字: 张量.cpu() for 名字, 张量 in 重要度.items()}
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    # ============================================================
    # 步骤 5：保存基座 A 的完整权重（供补丁应用/重置用）
    # ============================================================
    print("\n" + "=" * 60)
    print("步骤 5/10：保存基座 A 的完整权重")
    print("=" * 60)
    基座状态路径 = 配置.结果目录 / "基座A状态.pt"
    保存状态到磁盘(模型, 基座状态路径)
    基座状态 = 从磁盘读状态(基座状态路径)   # 直接读回，后面补丁计算差值要用

    # ============================================================
    # 步骤 6：全参数微调 A → 专家 B，并评估
    # ============================================================
    print("\n" + "=" * 60)
    print("步骤 6/10：全参数微调（这一步最慢，请耐心等待）")
    print("=" * 60)
    训练器 = 分类训练器(配置, 模型, 类别token编号)
    模型 = 训练器.训练(训练加载器)            # 原地微调，模型变成专家 B
    专家准确率 = 评估分类准确率(配置, 模型, 测试加载器, 类别token编号)
    print(f"全量微调后（专家 B）准确率：{专家准确率:.1%}")
    记录["专家准确率"] = 专家准确率
    # 保存专家 B 完整权重（备份，方便以后复现；可选）
    专家状态路径 = 配置.结果目录 / "专家B状态.pt"
    保存状态到磁盘(模型, 专家状态路径)
    # 拿专家 B 的参数索引（差值计算要用，注意这些张量在显存上）
    专家参数 = dict(模型.named_parameters())

    # ============================================================
    # 步骤 7：生成硬核补丁
    # ============================================================
    print("\n" + "=" * 60)
    print("步骤 7/10：生成硬核补丁")
    print("=" * 60)
    补丁对象列表 = []
    for 条目 in 配置.补丁清单:
        补丁 = 生成补丁文件(
            配置,
            名称=条目["名称"], 策略=条目["策略"], 比例=条目["比例"],
            重要度=重要度, 基座状态=基座状态, 专家参数=专家参数,
        )
        补丁对象列表.append(补丁)

    # ============================================================
    # 步骤 8：逐个补丁评估（重置为基座 → 盖补丁 → 测准确率）
    # ============================================================
    print("\n" + "=" * 60)
    print("步骤 8/10：评估每个补丁（重新加载基座）")
    print("=" * 60)
    # 全量微调占用的显存已不需要，先释放，再重新加载基座 A
    释放模型(模型)
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    模型, _ = 加载模型和分词器(配置)          # 重新加载一份干净的基座 A
    for 补丁 in 补丁对象列表:
        # 先重置为基座（保证上一次补丁的改动不影响这一次）
        重置模型为基座(模型, 基座状态)
        # 计时"切换一次专家"（显存内覆盖）
        切换毫秒 = 计时专家切换(配置, 模型, 补丁, 基座状态)
        # 盖补丁后评估
        准确率 = 评估分类准确率(配置, 模型, 测试加载器, 类别token编号)
        print(f"补丁「{补丁.元数据['名称']}」准确率：{准确率:.1%}")
        # 计算"恢复率"：把全量提升保住了百分之几
        分母 = 记录["专家准确率"] - 记录["基座准确率"]
        恢复率 = (准确率 - 记录["基座准确率"]) / 分母 if abs(分母) > 1e-9 else 0.0
        记录["补丁结果"].append({
            "名称": 补丁.元数据["名称"],
            "策略": 补丁.元数据["策略"],
            "比例": 补丁.元数据["目标比例"],
            "准确率": 准确率,
            "恢复率": 恢复率,
            "文件大小MB": 补丁.文件大小MB(),
            "实际占比": 补丁.实际占比(记录["模型参数总数"]),
            "切换毫秒": 切换毫秒,
        })

    # ============================================================
    # 步骤 9：LoRA 对照实验
    # ============================================================
    if 配置.是否跑LoRA基线:
        print("\n" + "=" * 60)
        print("步骤 9/10：训练 LoRA 对照组")
        print("=" * 60)
        for 秩 in 配置.LoRA秩列表:
            print(f"\n--- LoRA 秩 r={秩} ---")
            释放模型(模型)
            gc.collect()
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
            模型2, _ = 加载模型和分词器(配置)
            lora模型, 可训练参数 = 训练LoRA模型(配置, 模型2, 类别token编号, 训练加载器, 秩)
            # 直接评估（带 LoRA 旁路）
            lora准确率 = 评估分类准确率(配置, lora模型, 测试加载器, 类别token编号)
            # 合并 LoRA 进基座（变成普通权重，模拟"合并部署"）再评估
            try:
                lora合并模型 = lora模型.merge_and_unload()
                lora合并准确率 = 评估分类准确率(配置, lora合并模型, 测试加载器, 类别token编号)
                释放模型(lora合并模型)
            except Exception as 异常:
                print(f"LoRA 合并失败（{异常}），使用未合并的准确率")
                lora合并准确率 = lora准确率
            分母 = 记录["专家准确率"] - 记录["基座准确率"]
            恢复率 = (lora合并准确率 - 记录["基座准确率"]) / 分母 if abs(分母) > 1e-9 else 0.0
            记录["LoRA结果"].append({
                "秩": 秩,
                "准确率": lora合并准确率,
                "恢复率": 恢复率,
                "大小MB": 可训练参数 * 2 / (1024 ** 2),   # 估算：参数 × 2 字节(f16)
            })
            print(f"LoRA(r={秩}) 合并后准确率：{lora合并准确率:.1%}，适配器约 {可训练参数 * 2 / (1024 ** 2):.2f} MB")
        释放模型(模型)
    else:
        print("\n步骤 9/10：已跳过 LoRA 对照组（配置里 是否跑LoRA基线 = False）")

    # ============================================================
    # 步骤 10：汇总生成报告
    # ============================================================
    print("\n" + "=" * 60)
    print("步骤 10/10：生成报告")
    print("=" * 60)
    生成报告(配置, 记录)
    return 记录
