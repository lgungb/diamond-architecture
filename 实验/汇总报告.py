# -*- coding: utf-8 -*-
# ============================================================
# 文件：汇总报告.py
# 作用：把实验产生的所有结果整理成一份 Markdown 报告（结果/报告.md），
#       并在控制台打印出来。报告回答三个核心问题：
#         1. 全量微调比基座强多少？
#         2. 钻石架构的补丁恢复了多少提升？（恢复率）
#         3. LoRA 相比钻石架构如何？（准确率 vs 体积）
#
# 需要的条件：
#   - 不依赖第三方库，纯标准库。
# ============================================================

# ---------- 导入标准库 ----------
import time                     # 拿当前时间写进报告
from pathlib import Path        # 路径工具


def 生成报告(配置, 记录: dict) -> str:
    """把实验结果整理成 Markdown 报告并打印，返回报告文本。

    参数：记录 是一个字典，包含实验的所有关键数据：
      {
        "基座准确率": 浮点数,
        "专家准确率": 浮点数,
        "补丁结果":   [ {名称,策略,比例,准确率,恢复率,文件大小MB,实际占比,切换毫秒}, ... ],
        "LoRA结果":   [ {秩,准确率,大小MB}, ... ],
        "模型参数总数": 整数,
      }
    返回：报告文本（也已保存到 结果/报告.md）。
    """
    行 = []   # 收集报告的所有行，最后拼起来

    # ---------- 报告头部 ----------
    行.append("# 钻石架构验证实验报告")
    行.append("")
    行.append(f"- 生成时间：{time.strftime('%Y-%m-%d %H:%M:%S')}")
    行.append(f"- 模型：{配置.模型ID}")
    行.append(f"- 任务：{配置.数据来源}三分类任务（类别：{'、'.join(配置.任务类别)}）")
    行.append(f"- 模型参数总数：{记录['模型参数总数']:,}")
    行.append("")

    # ---------- 表1：总体对比 ----------
    行.append("## 一、总体对比（准确率）")
    行.append("")
    行.append("| 模型变体 | 准确率 | 相对全量微调的恢复率 |")
    行.append("| --- | ---: | ---: |")
    # 基座行
    行.append(f"| 基座 A（未微调） | {记录['基座准确率']:.1%} | — |")
    # 专家（全量微调）行：定义 100%
    行.append(f"| 全量微调 B（专家） | {记录['专家准确率']:.1%} | 100%（基准） |")
    # 补丁行
    for 单条 in 记录["补丁结果"]:
        行.append(
            f"| {单条['名称']} | {单条['准确率']:.1%} | {单条['恢复率']:.1%} |"
        )
    # LoRA 行
    for 单条 in 记录.get("LoRA结果", []):
        行.append(
            f"| LoRA(r={单条['秩']}) | {单条['准确率']:.1%} | {单条['恢复率']:.1%} |"
        )
    行.append("")
    行.append("> 恢复率 = (该变体准确率 - 基座准确率) / (全量微调准确率 - 基座准确率)，"
              "衡量它把微调带来的提升保住了百分之几。")
    行.append("")

    # ---------- 表2：补丁明细 ----------
    行.append("## 二、硬核补丁明细")
    行.append("")
    行.append("| 名称 | 策略 | 目标比例 | 文件大小(MB) | 实际替换占比 | 切换耗时(ms) |")
    行.append("| --- | --- | ---: | ---: | ---: | ---: |")
    for 单条 in 记录["补丁结果"]:
        行.append(
            f"| {单条['名称']} | {单条['策略']} | {单条['比例']:.0%} "
            f"| {单条['文件大小MB']:.2f} | {单条['实际占比']:.2%} | {单条['切换毫秒']:.2f} |"
        )
    行.append("")
    行.append("> 切换耗时 = 显存内覆盖耗时（不含从硬盘读补丁的时间）。")
    行.append("")

    # ---------- 表3：LoRA 明细 ----------
    if 记录.get("LoRA结果"):
        行.append("## 三、LoRA 对照明细")
        行.append("")
        行.append("| LoRA 秩 | 准确率 | 适配器大小(估算MB) |")
        行.append("| --- | ---: | ---: |")
        for 单条 in 记录["LoRA结果"]:
            行.append(f"| r={单条['秩']} | {单条['准确率']:.1%} | {单条['大小MB']:.2f} |")
        行.append("")
        行.append("> 适配器大小按 可训练参数 × 2 字节(f16) 估算，仅供参考。")
        行.append("")

    # ---------- 结论判定 ----------
    行.append("## 四、结论判定")
    行.append("")
    # 4.1 策略A 的核心论断验证
    A结果 = [单条 for 单条 in 记录["补丁结果"] if 单条["策略"] == "策略A"]
    if A结果:
        # 取 6% 那个（最有代表性），没有就取最后一个
        A代表 = max(A结果, key=lambda x: x["比例"])
        行.append(f"**策略A（高重要度）验证**：6% 比例的补丁恢复了全量提升的 "
                  f"**{A代表['恢复率']:.1%}**。")
        if A代表["恢复率"] >= 0.9:
            行.append("→ 恢复率 ≥ 90%，**支持**白皮书“逼近全量微调”的核心论断（在本任务上）。")
        elif A代表["恢复率"] >= 0.5:
            行.append("→ 恢复率在 50%~90% 之间，部分支持白皮书论断，但能力有可见损失。")
        else:
            行.append("→ 恢复率不足 50%，**不支持**白皮书论断，说明 6% 参数在本次任务上不够。")
        行.append("")
    # 4.2 策略B 的验证（低重要度是否"不改能力"）
    B结果 = [单条 for 单条 in 记录["补丁结果"] if 单条["策略"] == "策略B"]
    if B结果:
        B代表 = B结果[0]
        行.append(f"**策略B（低重要度）验证**：{B代表['名称']} 的准确率为 "
                  f"**{B代表['准确率']:.1%}**（基座 {记录['基座准确率']:.1%}）。")
        # 低重要度如果几乎不提升能力 → 支持"策略B不碰核心逻辑"的说法
        if abs(B代表["准确率"] - 记录["基座准确率"]) < 0.05:
            行.append("→ 准确率与基座基本持平：验证了白皮书“低重要度参数不改变核心能力”的说法。")
        else:
            行.append("→ 准确率明显高于基座：说明低重要度参数也能影响任务能力，"
                      "与白皮书“策略B只改风格”的定位不符。")
        行.append("")
    # 4.3 LoRA 与钻石架构的对比
    if 记录.get("LoRA结果"):
        行.append("**钻石架构 vs LoRA**：请对比上方表格中补丁与 LoRA 的【准确率】和【体积】。"
                  "如果补丁在相近体积下准确率更高，则“无低秩瓶颈”的卖点成立；否则需要说明。")
    行.append("")

    # ---------- 保存并打印 ----------
    报告文本 = "\n".join(行)
    报告路径 = 配置.结果目录 / "报告.md"
    Path(报告路径).parent.mkdir(parents=True, exist_ok=True)
    with open(报告路径, "w", encoding="utf-8") as 文件:
        文件.write(报告文本)
    print("\n" + "=" * 60)
    print("【实验报告】已生成：" + str(报告路径))
    print("=" * 60)
    print(报告文本)
    return 报告文本
