# -*- coding: utf-8 -*-
# ============================================================
# 文件：配置.py
# 作用：本项目的【唯一参数总控文件】。
#       所有可以调整的开关、数值、路径都集中在这里。
#       用户（不需要懂代码）只需修改本文件里的数值，
#       其余代码会自动读取这些配置。
#
# 需要的条件：
#   - 本文件不依赖任何第三方库，只用了 Python 自带的 pathlib 和 dataclasses。
#   - 项目根目录下必须存在这些子目录：配置/ 数据/ 模型/ 补丁/ 评估/ 实验/ 运行/ 工具/ 结果/
#
# 修改指引（给不懂代码的用户）：
#   - 想换模型：改【模型ID】这一项。
#   - 想让实验跑快一点先看效果：把【冒烟模式】改成 True。
#   - 想加/减补丁实验：改【补丁清单】列表里的条目。
#   - 想关掉 LoRA 对比：把【是否跑LoRA基线】改成 False。
# ============================================================

from pathlib import Path          # Python 自带的路径工具，跨系统都能用
from dataclasses import dataclass # Python 自带的"数据类"工具，用来声明一个整齐的配置结构


# ---------- 第一步：固定项目根目录 ----------
# 这个文件的上级目录的上级目录，就是整个项目的根目录。
# 不管代码被拉到哪台电脑，都能自动找到项目根，路径不会写死。
项目根目录 = Path(__file__).resolve().parent.parent


# ---------- 第二步：声明配置结构 ----------
@dataclass
class 配置项:
    """整个实验的全部参数都装在这个"配置对象"里。

    说明：dataclass 会自动生成一个构造器，我们下面直接给每个字段填默认值。
    其它代码通过【配置.字段名】来读取，例如 配置.模型ID。
    """

    # ==================== 一、模型相关 ====================
    模型ID: str = "Qwen/Qwen3.5-2B"
    """魔搭(modelscope)上的模型编号。Qwen3.5-2B 就是用户指定的目标模型。
    注意：Qwen3.5 是"多模态"模型（文字+图像+音频都能输入），
    所以加载时如果普通文本加载失败，代码会自动改用多模态方式加载。
    如果将来想换模型，把这里换成别的模型 ID 即可。"""

    模型缓存目录: Path = 项目根目录 / "缓存" / "模型"
    """模型第一次从网上下载后，会保存在这个本地目录里（免得每次重下）。
    这个目录被 .gitignore 忽略，不会上传到 GitHub。"""

    是否强制重新下载: bool = False
    """模型是否强制重新下载（通常不用改）：
      - False（推荐）：运行前先检查本地缓存，已有模型就直接用，不联网下载。
      - True          ：忽略本地缓存，强制从魔搭重新下载（用于模型文件损坏/想更新时）。"""

    加载方式: str = "自动"
    """模型加载策略，可选三种：
      - "自动"  ：先试文本方式(AutoModelForCausalLM)，失败自动换多模态方式(最省心，推荐)
      - "纯文本"：强制用文本方式加载（适合纯文本版 Qwen3.5）
      - "多模态"：强制用多模态方式加载（Qwen3.5-2B 原版用这个）
    """

    数据类型: str = "bfloat16"
    """模型权重加载成什么精度。Qwen3.5 官方推荐 bfloat16（简称 bf16）。
    可选："bfloat16"（推荐，范围大更稳）或 "float16"（老显卡兼容）。"""

    设备: str = "cuda"
    """计算设备。"cuda" 用显卡（modelscope notebook 有免费 GPU，推荐）；
    "cpu" 用 CPU（非常慢，只有实在没显卡时才用）。"""

    # ==================== 二、任务与数据相关 ====================
    数据来源: str = "合成"
    """任务数据从哪来：
      - "合成"：程序自己生成一套"三分类密语"任务（默认，离线可用，不需要联网下载数据，
                基座模型没见过这些密语词所以正确率接近随机，最适合验证微调效果）
      - "真实"：从魔搭下载真实中文分类数据集（需要在【真实数据.py】里配置数据集 ID）
    """

    任务类别: tuple = ("甲", "乙", "丙")
    """分类任务的三个类别标签。用单字中文最稳（分词后一定是单个 token）。
    如果模型不认识这些字（几乎不可能），代码会报错提示你换词。"""

    每类训练条数: int = 600
    """每个类别生成多少条【训练】数据。三类合计 1800 条，够微调用了。"""

    每类测试条数: int = 200
    """每个类别生成多少条【测试】数据（测试数据绝不参与训练，用于算准确率）。"""

    每类校准条数: int = 40
    """每个类别抽多少条【校准】数据（用于计算 Fisher 重要度，衡量每个参数对任务多重要）。"""

    最大序列长度: int = 128
    """每条文本最多切多少个 token，超出部分截断。128 足够这类短文本任务用。"""

    随机种子: int = 42
    """随机种子。固定后每次运行生成的句子、打乱的顺序都一样，保证实验可复现。"""

    # ==================== 三、全参数微调相关 ====================
    学习率: float = 3e-5
    """微调学习率。3e-5 是 Qwen 微调的常用值。"""

    批次大小: int = 4
    """一次前向放进多少条样本。显卡显存不够就调小（2 或 1）。"""

    梯度累积步数: int = 4
    """攒够多少步才更新一次参数，等效于把批次放大到 批次大小×累积步数。
    显存小也能用大批次效果，这是标准做法。"""

    训练轮数: int = 3
    """把训练集完整过几遍。任务简单，3 轮足够。"""

    最大训练步数: int = 0
    """最多训练多少步（0 表示不限制，按轮数跑完）。
    冒烟测试时设成例如 60，几秒钟就能看到完整流程走通。"""

    是否开启梯度检查点: bool = True
    """梯度检查点：用"多算几次"换"省显存"，对 2B 全参数微调很有必要，推荐保持 True。"""

    训练精度: str = "bfloat16"
    """训练时用的混合精度。Qwen3.5 建议 bfloat16（显卡支持 bf16 时）。"""

    优化器: str = "adafactor"
    """用什么优化器微调：
      - "adafactor"（推荐）：内存占用极小，2B 全参微调在 24G 显卡上必须用它，
                否则 AdamW 需要约 27GB 的 fp32 优化器状态，显卡根本装不下（会爆显存）。
      - "adamw"（可选）    ：经典优化器，效果更稳，但 2B 全参微调需要大显存，容易 OOM。
    效果上对这个简单分类任务两者都能达到接近满分，选 adafactor 最省心。"""

    # ==================== 四、Fisher 重要度计算相关 ====================
    Fisher校准条数: int = 60
    """计算 Fisher 时实际用多少条校准数据（不能超过每类校准条数×类别数）。
    数量越大越准确，但越慢。60 条足够。"""

    Fisher所在模型: str = "基座"
    """在哪个模型上计算参数重要性：
      - "基座"：在未微调的基础模型 A 上算（标准做法，也是白皮书的意图，推荐）
      - "专家"：在微调后的专家模型 B 上算（先不做，留作扩展）
    """

    # ==================== 五、硬核补丁实验相关 ====================
    补丁清单: tuple = (
        {"名称": "策略A_2%", "策略": "策略A", "比例": 0.02},
        {"名称": "策略A_4%", "策略": "策略A", "比例": 0.04},
        {"名称": "策略A_6%", "策略": "策略A", "比例": 0.06},
        {"名称": "策略B_2%", "策略": "策略B", "比例": 0.02},
        {"名称": "策略C_6%", "策略": "策略C", "比例": 0.06},
    )
    """要生成并测试哪些"硬核补丁"。每个条目是一份补丁的说明：
       - 名称：给这份补丁起个名字（会用在文件名里）
       - 策略：三种筛选策略之一（策略A=高重要度TopK / 策略B=低重要度BottomK / 策略C=高中低混合）
       - 比例：替换的参数占总参数的百分比（2% 就是 0.02）
    想加实验就在这里加条目，想删就删条目，不用改任何代码。"""

    阈值过滤: float = 1e-4
    """白皮书"步骤6"的可选过滤：被选中位置上的差值Δ，如果绝对值小于这个阈值，
    说明改动极小、对输出几乎没影响，就从补丁里剔除，进一步缩小补丁体积。
    设成 None 表示不做过滤。"""

    # ==================== 六、LoRA 对比基线相关 ====================
    是否跑LoRA基线: bool = True
    """是否训练 LoRA 作为对照组。LoRA 是业界最常用的轻量微调方法，
    和钻石架构直接对比，才能看出"谁省、谁准"。"""

    LoRA秩列表: tuple = (16, 64)
    """LoRA 的两个秩（r）配置。秩越大能学的东西越多，但补丁也越大。"""

    # ==================== 七、输出与调试相关 ====================
    结果目录: Path = 项目根目录 / "结果"
    """所有实验结果（补丁文件、模型状态、报告）都存到这个目录。"""

    补丁目录: Path = 项目根目录 / "结果" / "补丁"
    """生成的硬核补丁文件专门放这里。"""

    冒烟模式: bool = False
    """冒烟测试开关：True 时把所有规模大幅缩小（数据少、步数少），
    目的是几分钟内验证整套流程能跑通，跑通后再关掉跑正式实验。
    正式实验请保持 False。"""

    是否显示详细日志: bool = True
    """True 时打印每一步的详细进度和中间结果，方便你观察实验在干什么。"""

    # ==================== 八、派生配置（由上面自动算出，不用手改） ====================
    @property
    def 有效批次大小(self) -> int:
        """等效批次大小 = 批次大小 × 梯度累积步数（只读属性，不用改）。"""
        return self.批次大小 * self.梯度累积步数


# ---------- 第三步：创建全局唯一的配置实例 ----------
# 其它代码统一用【from 配置.配置 import 配置】来拿到这个配置对象。
配置 = 配置项()
