# ============================================================
# 文件：应用补丁.py
# 作用：实现白皮书"推理时参数替换机制"和"多专家切换"：
#       1. 重置模型为基座状态（把可能被上次补丁改动的位置还原）。
#       2. 把一份补丁"盖"到模型上（只改被选中的那 2%~6% 位置）。
#       3. 计时"切换一次专家"要花多少毫秒（模拟毫秒级切换的验证）。
#
# 关键概念：补丁里存的是【差值 Δ】。应用补丁时，在对应位置上执行
#          新值 = 当前值 + Δ。因为应用前模型是基座值 A，
#          所以结果正好是 专家值 B = A + Δ，等价于"物理替换"。
#
# 需要的条件：
#   - 依赖 torch。
# ============================================================

# ---------- 导入标准库 ----------
import time                          # 计时
import torch                         # 深度学习框架

# ---------- 导入本项目 ----------
from 模型.模型工具 import 把状态载入模型   # 复用"载入状态"的工具函数


# ---------- 一、重置模型为基座 ----------
def 重置模型为基座(模型, 基座状态: dict):
    """把模型权重整体还原成基座状态 A。

    为什么需要：评估多个补丁时，上一个补丁改过的位置还残留着，
    必须先把模型还原成 A，再应用下一个补丁，才互不干扰。
    参数：
      模型     ：目标模型。
      基座状态 ：基座 A 的完整状态字典（从磁盘读回，见 模型工具.py）。
    """
    把状态载入模型(模型, 基座状态)   # 一句搞定


# ---------- 二、把补丁盖到模型上 ----------
def 应用补丁到模型(模型, 补丁) -> int:
    """把一份补丁原地应用到模型上，返回一共改了多少个位置。

    参数：
      模型 ：目标模型（应用前必须是基座状态 A）。
      补丁 ：补丁文件 对象。
    返回：
      被修改的参数位置数量。
    """
    参数字典 = dict(模型.named_parameters())   # 建立"参数名 → 参数张量"索引
    改动数 = 0
    for 名字, 条目 in 补丁.参数条目.items():
        参数 = 参数字典[名字]                   # 找到这个参数张量
        平展 = 参数.data.view(-1)               # 拉平成一维，方便按位置改
        # 把索引和差值搬到参数所在设备，并转成同样的精度
        索引 = 条目["索引"].to(参数.device)
        差值 = 条目["差值"].to(参数.device).to(参数.dtype)
        # 关键一步：新值 = 当前值(基座A) + 差值(Δ) = 专家值(B)
        平展[索引] += 差值
        改动数 += len(索引)
    return 改动数


# ---------- 三、计时一次专家切换 ----------
def 计时专家切换(配置, 模型, 补丁, 基座状态: dict) -> float:
    """模拟一次"切换专家"的耗时：重置为基座 → 应用补丁，返回毫秒数。

    说明：这是在【显存内】的覆盖耗时（对应白皮书"毫秒级切换"）。
    注意：如果补丁要从硬盘加载，还得加上磁盘读取时间（通常几十到几百毫秒）。
    参数：
      配置     ：配置项对象（用于打印）。
      模型     ：目标模型。
      补丁     ：要应用的补丁。
      基座状态 ：基座 A 状态字典。
    返回：
      覆盖耗时（毫秒）。
    """
    # 先保证是基座状态
    重置模型为基座(模型, 基座状态)
    # 同步一下，确保前面的操作都完成，计时才准
    torch.cuda.synchronize()
    开始时刻 = time.perf_counter()          # 开始计时
    应用补丁到模型(模型, 补丁)               # 执行覆盖
    torch.cuda.synchronize()
    结束时刻 = time.perf_counter()          # 结束计时
    耗时毫秒 = (结束时刻 - 开始时刻) * 1000
    if 配置.是否显示详细日志:
        print(f"  切换耗时：{耗时毫秒:.2f} 毫秒（显存内覆盖，不含硬盘加载）")
    return 耗时毫秒
