# -*- coding: utf-8 -*-
# ============================================================
# 文件：补丁格式.py
# 作用：定义"硬核补丁"的数据结构，以及它的保存/读取方法。
#
# 什么是硬核补丁（对应白皮书）：
#   全参数微调得到专家模型 B 后，B 相对基座 A 每个参数都变了（Δ = B - A）。
#   但我们只把其中"被选中的少数参数"（2%~6%）的差值保存下来，
#   这份"位置索引 + 差值"的集合，就是一个硬核补丁。
#   推理时把这个补丁盖到基座 A 的对应位置，就得到"接近专家 B 的能力"。
#
# 需要的条件：
#   - 依赖 torch（用于保存/读取张量）。
# ============================================================

# ---------- 导入标准库 ----------
from dataclasses import dataclass, field   # 数据类（自动生成初始化方法）
from pathlib import Path                   # 路径工具
import torch                               # 深度学习框架


# ---------- 定义补丁文件的数据结构 ----------
@dataclass
class 补丁文件:
    """一份硬核补丁。

    两个字段：
      元数据   ：描述这份补丁的说明信息（策略、比例、基座模型等），不参与计算。
      参数条目 ：核心内容 {参数名: {"索引": 被替换位置(整数张量), "差值": 该位置的 Δ 值}}。
    """
    元数据: dict = field(default_factory=dict)          # 说明信息
    参数条目: dict = field(default_factory=dict)        # 位置 + 差值

    # ---------- 保存 ----------
    def 保存(self, 保存路径) -> str:
        """把补丁保存成 .pt 文件。

        参数：保存路径 存到哪里。
        返回：保存路径。
        """
        保存路径 = str(保存路径)
        # 先把要保存的目录建好
        Path(保存路径).parent.mkdir(parents=True, exist_ok=True)
        # torch.save 可以一次性把整个字典写进一个文件
        torch.save({"元数据": self.元数据, "参数条目": self.参数条目}, 保存路径)
        return 保存路径

    # ---------- 读取 ----------
    @classmethod
    def 加载(cls, 读取路径) -> "补丁文件":
        """从 .pt 文件读回一份补丁。

        参数：读取路径 文件在哪。
        返回：补丁文件 对象。
        """
        读取路径 = str(读取路径)
        数据 = torch.load(读取路径, map_location="cpu", weights_only=True)
        return cls(元数据=数据["元数据"], 参数条目=数据["参数条目"])

    # ---------- 统计 ----------
    def 文件大小MB(self) -> float:
        """估算这份补丁在磁盘上大概占多少 MB（把所有张量的字节数加起来）。"""
        总字节 = 0
        for 条目 in self.参数条目.values():
            # 索引是 int64（8 字节/个），差值是 fp16（2 字节/个）
            总字节 += 条目["索引"].numel() * 8 + 条目["差值"].numel() * 2
        return 总字节 / (1024 ** 2)

    def 实际替换参数数量(self) -> int:
        """数一数这份补丁一共替换了多少个参数。"""
        return sum(条目["索引"].numel() for 条目 in self.参数条目.values())

    def 实际占比(self, 总参数数: int) -> float:
        """这份补丁实际替换的参数占全模型的比例（因为阈值过滤可能比目标比例小）。"""
        return self.实际替换参数数量() / 总参数数 if 总参数数 else 0.0
