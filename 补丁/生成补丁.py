# ============================================================
# 文件：生成补丁.py
# 作用：实现白皮书"步骤 4：筛选关键参数" + "步骤 5：保存硬核补丁文件"。
#       核心分两步：
#         第一步【选择位置】：按三种策略（A/B/C）从所有参数里挑出要替换的 2%~6%。
#         第二步【计算差值】：在挑中的位置上，计算 专家B - 基座A 的差值 Δ。
#       最后把"位置 + 差值 + 元数据"打包成一份补丁文件。
#
# 三种策略（对应白皮书）：
#   策略A：选 Fisher 重要度【最高】的 Top K 参数 → 替换的是"计算主干"，改能力。
#   策略B：选 Fisher 重要度【最低】的 Bottom K 参数 → 据说只扰动边缘，改风格。
#   策略C：高 2% + 低 2% + 中 2% 混合 → 兼顾能力与风格。
#   （注意：策略C的"中"段这里按每个张量内部取中段近似实现，见函数注释）
#
# 需要的条件：
#   - 依赖 torch。
#   - 需要传入：Fisher 重要度、基座状态 A、专家参数 B。
# ============================================================

# ---------- 导入标准库 ----------
import math                              # 数学函数（向上取整等）
import time                              # 计时用
import torch                             # 深度学习框架

# ---------- 导入本项目 ----------
from 补丁.补丁格式 import 补丁文件          # 补丁数据结构


# ============================================================
# 第一步：选择要替换的参数位置
# ============================================================
def 选择补丁位置(重要度: dict, 策略: str, 比例: float) -> dict:
    """根据策略，从所有参数中挑出要替换的位置。

    参数：
      重要度 ：Fisher 重要度字典 {参数名: 张量}（数值越大越重要）。
      策略   ："策略A" / "策略B" / "策略C"。
      比例   ：要替换的参数占总参数的百分比（0.02 表示 2%）。
    返回：
      位置字典 {参数名: 局部索引张量}，局部索引是"在该参数内部"的扁平位置。
    """
    # 按策略分流到不同实现
    if 策略 == "策略A":
        return _全局选Top(重要度, 比例, 取高分=True)     # 高重要度 TopK
    if 策略 == "策略B":
        return _全局选Top(重要度, 比例, 取高分=False)    # 低重要度 BottomK
    if 策略 == "策略C":
        return _混合选三段(重要度, 比例)                  # 高 + 低 + 中
    raise ValueError(f"未知策略：{策略}，只能是 策略A/策略B/策略C")


def _全局选Top(重要度: dict, 比例: float, 取高分: bool) -> dict:
    """策略A / 策略B 的位置选择：在全模型范围内按重要度排序，取最高（或最低）的一批。

    实现说明（两阶段，控制显存）：
      第一阶段：每个参数张量内部先各自取"放宽 10 倍"的候选位置；
      第二阶段：把所有候选合在一起，再做一次全局排序，精确取到目标数量。
      这样峰值内存只占"候选数"那么多，而不是全模型那么大。
    """
    总参数数 = sum(张量.numel() for 张量 in 重要度.values())          # 全模型参数个数
    目标数量 = max(1, int(总参数数 * 比例))                            # 要选多少个
    放大系数 = 10                                                     # 候选放宽倍数
    段信息 = []    # 每个元素 (参数名, 该参数内选出的局部索引, 对应分数)
    # ---- 第一阶段：每张量内部取候选 ----
    for 名字, 张量 in 重要度.items():
        平展 = 张量.reshape(-1).float()                               # 拉平成 1 维
        # 按"占全模型比例"给这个张量分配候选名额（至少 1 个，不超过张量本身）
        候选名额 = max(1, min(张量.numel(),
                       int(math.ceil(目标数量 * 放大系数 * 张量.numel() / 总参数数))))
        # 取高分就按分数降序 topk，取低分就按负分数降序 topk
        排序用 = 平展 if 取高分 else (-平展)
        局部索引 = torch.topk(排序用, 候选名额).indices.cpu()          # 候选位置
        局部分数 = 平展[局部索引].cpu()                                # 候选分数
        段信息.append((名字, 局部索引, 局部分数))
    # ---- 第二阶段：合并后全局精筛 ----
    合并分数 = torch.cat([段[2] for 段 in 段信息])                     # 所有候选分数拼起来
    合并排序用 = 合并分数 if 取高分 else (-合并分数)
    全局序号 = torch.topk(合并排序用, min(目标数量, len(合并分数))).indices  # 全局前 K 在合并里的位置
    # 把"合并里的位置"映射回"哪个参数、参数里的哪个局部位置"
    各段长度 = torch.tensor([len(段[1]) for 段 in 段信息])             # 每段长度
    前缀和 = torch.cat([torch.zeros(1, dtype=torch.long),
                        torch.cumsum(各段长度, dim=0)])                # 每段起始偏移
    段归属 = torch.searchsorted(前缀和, 全局序号, right=True) - 1       # 第几段
    段内位 = 全局序号 - 前缀和[段归属]                                  # 段内第几个
    结果 = {}
    for 序号 in range(len(全局序号)):
        段号 = int(段归属[序号])
        名字, 局部索引, _ = 段信息[段号]
        结果.setdefault(名字, []).append(int(局部索引[int(段内位[序号])]))
    return {名字: torch.tensor(索引列表, dtype=torch.long) for 名字, 索引列表 in 结果.items()}


def _混合选三段(重要度: dict, 总比例: float) -> dict:
    """策略C的位置选择：每个张量内部取 高2% + 低2% + 中2%，合计约 总比例(6%)。

    说明：白皮书把策略C描述为"高评分2% + 低评分2% + 中评分2%"。
    这里"中评分"实现为：按分数排序后取正中间那 2%（既不高也不低）。
    为了实现简单且稳定，策略C按"每个张量内部"选择（策略A/B 是全局选择），
    总量上仍约等于 6%，但分布略偏局部——这在验证实验中可接受。
    """
    单段比例 = 总比例 / 3    # 高/低/中各占多少（0.06 / 3 = 0.02）
    结果 = {}
    for 名字, 张量 in 重要度.items():
        平展 = 张量.reshape(-1).float()
        数量 = 张量.numel()
        每段数 = max(1, int(数量 * 单段比例))       # 每段取多少个
        每段数 = min(每段数, 数量)
        # 1) 高分段：分数最高的
        高索引 = torch.topk(平展, 每段数).indices
        # 2) 低分段：分数最低的
        低索引 = torch.topk(-平展, 每段数).indices
        # 3) 中分段：按分数升序排序后，取正中间一段
        if 数量 >= 3 * 每段数:
            升序索引 = torch.argsort(平展)
            起点 = (数量 - 每段数) // 2
            中索引 = 升序索引[起点:起点 + 每段数]
        else:
            中索引 = torch.empty(0, dtype=torch.long, device=平展.device)
        # 三段合并，得到这个张量要替换的所有位置
        结果[名字] = torch.cat([高索引, 低索引, 中索引]).cpu()
    return 结果


# ============================================================
# 第二步：计算差值并打包成补丁文件
# ============================================================
def 生成补丁文件(配置, 名称: str, 策略: str, 比例: float,
                重要度: dict, 基座状态: dict, 专家参数: dict) -> 补丁文件:
    """根据位置选择 + 差值计算，生成并保存一份补丁文件。

    参数：
      配置      ：配置项对象（含 阈值过滤、补丁目录）。
      名称      ：这份补丁的名字（用于文件名和元数据）。
      策略      ："策略A"/"策略B"/"策略C"。
      比例      ：目标替换比例。
      重要度    ：Fisher 重要度（用于选位置）。
      基座状态  ：基座模型 A 的完整状态字典（从磁盘读回）。
      专家参数  ：专家模型 B 的参数字典（从训练好的模型拿，一般在显存里）。
    返回：
      补丁文件 对象（已经保存到 结果/补丁/ 目录）。
    """
    print(f"\n正在生成补丁：{名称}（策略 {策略}，目标比例 {比例:.0%}）")
    # 1) 选位置
    位置 = 选择补丁位置(重要度, 策略, 比例)
    已选数 = sum(len(索引) for 索引 in 位置.values())
    print(f"  已选中参数位置 {已选数:,} 个（约 {已选数 / sum(张量.numel() for 张量 in 重要度.values()):.2%}）")
    # 2) 逐张量计算差值 Δ = B - A，并做阈值过滤
    参数条目 = {}
    被过滤数 = 0
    for 名字, 索引 in 位置.items():
        基座张量 = 基座状态[名字].float()                  # 基座 A 的权重（CPU）
        专家张量 = 专家参数[名字].detach().float()         # 专家 B 的权重（可能在显卡上）
        平展A = 基座张量.view(-1)
        平展B = 专家张量.view(-1)
        # 注意设备问题：索引默认在 CPU，要取专家 B 的值时先搬到 B 所在设备，
        # 取完再搬回 CPU，和基座 A 的 CPU 值做减法，避免跨设备报错。
        索引设备 = 索引.to(专家张量.device)
        差值 = 平展B[索引设备].cpu() - 平展A[索引]         # 被选位置上的 Δ = B - A
        # 白皮书"步骤6"的可选阈值过滤：改动太小的位置直接去掉，进一步压缩补丁
        if 配置.阈值过滤 is not None:
            保留掩码 = 差值.abs() >= 配置.阈值过滤
            被过滤数 += int((~保留掩码).sum().item())
            索引 = 索引[保留掩码]
            差值 = 差值[保留掩码]
        # 转成 CPU + 紧凑格式再存（索引用 int64，差值用 fp16）
        参数条目[名字] = {
            "索引": 索引.cpu().long(),
            "差值": 差值.cpu().half(),
        }
    # 3) 组装元数据
    元数据 = {
        "名称": 名称,
        "策略": 策略,
        "目标比例": 比例,
        "基座模型": 配置.模型ID,
        "生成时间": time.strftime("%Y-%m-%d %H:%M:%S"),
        "阈值过滤": 配置.阈值过滤,
        "过滤掉的参数数": 被过滤数,
    }
    补丁 = 补丁文件(元数据=元数据, 参数条目=参数条目)
    # 4) 保存到 结果/补丁/ 目录
    保存路径 = 配置.补丁目录 / f"{名称}.pt"
    补丁.保存(保存路径)
    print(f"  补丁已保存：{保存路径}")
    print(f"  补丁大小约 {补丁.文件大小MB():.2f} MB，"
          f"实际替换 {补丁.实际替换参数数量():,} 个参数（阈值过滤掉 {被过滤数:,} 个）")
    return 补丁
