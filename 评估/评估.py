# -*- coding: utf-8 -*-
# ============================================================
# 文件：评估.py
# 作用：在测试集上评估一个模型的【分类准确率】。
#       这是整个实验的"裁判"：谁准谁不准，用同一套标准说话。
#
# 原理：把测试句子按提示模板拼好喂给模型，看模型在句子末尾
#       预测的下一个词是不是正确答案（甲/乙/丙）。
#
# 需要的条件：
#   - 依赖 torch。
#   - 需要传入：模型、测试数据加载器、类别词 token 编号。
# ============================================================

import torch                          # 深度学习框架


def 评估分类准确率(配置, 模型, 测试数据加载器, 类别token编号: torch.Tensor) -> float:
    """在测试集上计算模型的分类准确率（0~1 之间，1 表示全对）。

    参数：
      配置             ：配置项对象。
      模型             ：要评估的模型（基座 / 专家 / 补丁版 / LoRA 都可以）。
      测试数据加载器    ：测试集 DataLoader。
      类别token编号     ：三个类别词在词表中的编号，形状 (3,)。
    返回：
      准确率（浮点数，例如 0.98 表示 98%）。
    """
    设备 = next(模型.parameters()).device
    模型.eval()                     # 切到评估模式（关 dropout，结果稳定）
    类别token编号 = 类别token编号.to(设备)
    正确数 = 0                       # 猜对的条数
    总条数 = 0                       # 一共多少条
    # 评估不需要算梯度，用 no_grad 省显存
    with torch.no_grad():
        for 批次 in 测试数据加载器:
            输入编号 = 批次["输入编号"].to(设备)
            注意力掩码 = 批次["注意力掩码"].to(设备)
            标签编号 = 批次["标签编号"].to(设备)
            # 混合精度前向（和训练一致，省显存；CPU 上不启用）
            训练精度 = torch.bfloat16 if 配置.训练精度 == "bfloat16" else torch.float16

            def 算前向():
                """内部小函数：执行一次前向，返回最后位置的类别得分。"""
                输出 = 模型(input_ids=输入编号, attention_mask=注意力掩码)
                logits = 输出.logits if hasattr(输出, "logits") else 输出[0]
                # 取最后一个位置在三个类别词上的得分，形状 (批次, 3)
                return logits[:, -1, 类别token编号]

            if 设备.type == "cuda":
                with torch.autocast(device_type="cuda", dtype=训练精度):
                    类别得分 = 算前向()
            else:
                类别得分 = 算前向()
            # 得分最高的那个类别就是模型的预测
            预测 = 类别得分.argmax(dim=-1)
            正确数 += (预测 == 标签编号).sum().item()
            总条数 += 标签编号.size(0)
    # 避免除零
    if 总条数 == 0:
        return 0.0
    return 正确数 / 总条数
