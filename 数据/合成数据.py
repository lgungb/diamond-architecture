# ============================================================
# 文件：合成数据.py
# 作用：生成一套"三分类密语任务"的训练/测试/校准数据。
#       这是本实验的默认任务，设计要点如下：
#        1. 三个类别：甲 / 乙 / 丙。
#        2. 每个类别绑定几个【生造的密语词】（例如"辉光藤蔓"）。
#           这些词是程序编出来的，预训练模型从未见过，
#           所以基座模型猜对的概率约等于瞎猜（1/3），
#           而微调之后模型能学会"看到某词 → 某类"，准确率接近 100%。
#        3. 用"密语词 + 多种句子模板"组合出多样化的句子，避免模型只会死记模板。
#       用这种"纯净"的任务来验证钻石架构，效果最清楚：
#       —— 全量微调能学到什么、补丁保住了多少，一目了然。
#
# 需要的条件：
#   - 需要传入一个 transformers 的分词器（用于把中文句子切成 token）。
#   - 不需要联网，不需要下载任何数据集。
# ============================================================

# ---------- 导入第三方库 ----------
import random                       # 用来随机生成句子和打乱顺序
from torch.utils.data import Dataset # torch 官方数据集的基类

# 第三方库在函数内再 import torch（见下方），这里只 import 从 torch.utils.data 拿基类
import torch


# ---------- 一、任务"配方"：密语词表和句子模板 ----------
# 每个类别的密语词（全部是生造词，模型没见过，这样才能测出微调的效果）
密语词表 = {
    "甲": ["辉光藤蔓", "青岚法典", "星尘决议"],
    "乙": ["熔岩矩阵", "赤霄敕令", "玄铁脉冲"],
    "丙": ["冰晶罗盘", "霜月禁制", "苍雷印文"],
}

# 句子模板：把密语词填进去，就得到一句待分类的消息。
# 多个模板是为了让同类的句子长得不一样，防止模型只背模板。
句子模板表 = [
    "目标物携带{词}的辐射特征",
    "档案记录显示{词}异常活跃",
    "检测器捕捉到{词}的波动信号",
    "任务日志中标记了{词}事件",
    "例行巡检发现{词}残留",
]


def 生成一句(类别: str, 随机源: random.Random) -> str:
    """随机生成一句属于【类别】的消息文本。

    参数：
      类别   ："甲" / "乙" / "丙" 之一。
      随机源 ：一个 random.Random 对象（固定种子就能复现）。
    返回：
      一个字符串句子，例如"检测器捕捉到辉光藤蔓的波动信号"。
    """
    词表 = 密语词表[类别]                    # 取该类别的全部密语词
    词 = 随机源.choice(词表)                # 随机挑一个密语词
    模板 = 随机源.choice(句子模板表)        # 随机挑一个句子模板
    return 模板.format(词=词)               # 把词填进模板，得到完整句子


# ---------- 二、自定义数据集类 ----------
class 分类数据集(Dataset):
    """把"句子 + 标签"包装成 PyTorch 可以直接使用的数据集。

    核心逻辑：
      - 构造时把每条句子用【分类提示模板】拼好，再切分成 token。
      - 所有样本统一补长到【最大序列长度】，这样批量取数据时形状整齐，不用再写复杂的合并逻辑。
      - 每条样本保存三个东西：
          输入编号    ：句子切分后的 token 编号（用于喂给模型）
          注意力掩码  ：1 表示是真实内容，0 表示是补的空白
          标签编号    ：这条样本属于哪个类别（0=甲，1=乙，2=丙）
    """

    # 分类提示模板：把待分类的句子嵌进去，让模型读完句子后在末尾输出类别。
    # 模板以"类别是："结尾，模型下一个要预测的 token 就是"甲/乙/丙"。
    分类提示模板 = "以下是一段需要分类的消息：\n{句子}\n\n这条消息的类别是："

    def __init__(self, 样本列表: list, 分词器, 类别到编号: dict, 最大长度: int):
        """初始化数据集。

        参数：
          样本列表 ：形如 [(句子, 类别), (句子, 类别), ...] 的列表。
          分词器   ：transformers 的分词器，负责把中文切成 token。
          类别到编号：字典，例如 {"甲": 0, "乙": 1, "丙": 2}。
          最大长度 ：每条样本最多保留多少个 token（超出截断，不足补空白）。
        """
        # 先取分词器的补位符号；Qwen 系列可能没设，就用结束符代替
        if 分词器.pad_token_id is None:
            分词器.pad_token = 分词器.eos_token   # 把结束符当作补位符（标准做法）
        self.样本 = []  # 最终存放处理好的样本
        # 逐条处理
        for 句子, 类别 in 样本列表:
            # 1) 用提示模板拼出完整输入文本
            完整文本 = self.分类提示模板.format(句子=句子)
            # 2) 切分成 token，超出最大长度就截断
            切分结果 = 分词器(完整文本, max_length=最大长度, truncation=True)
            编号列表 = 切分结果["input_ids"]
            掩码列表 = 切分结果["attention_mask"]
            # 3) 不足最大长度的部分用补位符补上，掩码补 0（0 表示"这是空白，别当真"）
            编号列表 = 编号列表 + [分词器.pad_token_id] * (最大长度 - len(编号列表))
            掩码列表 = 掩码列表 + [0] * (最大长度 - len(掩码列表))
            # 4) 把这条样本存起来（类别转成编号）
            self.样本.append((编号列表, 掩码列表, 类别到编号[类别]))
        # 全部转成 torch 张量，一次成型，后面取数据就快了
        self.输入编号 = torch.tensor([条[0] for 条 in self.样本], dtype=torch.long)
        self.注意力掩码 = torch.tensor([条[1] for 条 in self.样本], dtype=torch.long)
        self.标签编号 = torch.tensor([条[2] for 条 in self.样本], dtype=torch.long)

    def __len__(self) -> int:
        """返回数据集一共有多少条样本（PyTorch 约定方法）。"""
        return len(self.样本)

    def __getitem__(self, 序号: int) -> dict:
        """按序号取一条样本，返回一个字典（PyTorch 约定方法）。

        DataLoader 会自动把这些单条样本堆叠成一批。
        """
        return {
            "输入编号": self.输入编号[序号],      # 句子的 token 编号
            "注意力掩码": self.注意力掩码[序号],  # 哪些是真内容
            "标签编号": self.标签编号[序号],      # 类别编号
        }


# ---------- 三、构建三套数据集的入口函数 ----------
def 构建(配置, 分词器):
    """根据配置生成训练集 / 测试集 / 校准集，返回四样东西。

    参数：
      配置   ：配置项对象（见 配置/配置.py）。
      分词器 ：transformers 分词器。
    返回：
      (训练集, 测试集, 校准集, 类别到编号)
      其中三个数据集都是【分类数据集】对象；
      类别到编号 是 {"甲":0,"乙":1,"丙":2} 这种字典，供训练/评估使用。
    """
    # 1) 用固定种子创建一个独立的随机源（保证每次生成的句子一模一样）
    随机源 = random.Random(配置.随机种子)

    # 2) 分别收集训练、测试、校准的原始样本（句子, 类别）
    训练样本, 测试样本, 校准样本 = [], [], []
    for 类别 in 配置.任务类别:
        # 每个类别生成指定条数的句子
        for _ in range(配置.每类训练条数):
            训练样本.append((生成一句(类别, 随机源), 类别))
        for _ in range(配置.每类测试条数):
            测试样本.append((生成一句(类别, 随机源), 类别))
        for _ in range(配置.每类校准条数):
            校准样本.append((生成一句(类别, 随机源), 类别))

    # 3) 打乱顺序（防止同类样本挤在一起）
    随机源.shuffle(训练样本)
    随机源.shuffle(测试样本)
    随机源.shuffle(校准样本)

    # 4) 类别转编号：{"甲":0, "乙":1, "丙":2}
    类别到编号 = {类别: 序号 for 序号, 类别 in enumerate(配置.任务类别)}

    # 5) 包装成数据集对象
    训练集 = 分类数据集(训练样本, 分词器, 类别到编号, 配置.最大序列长度)
    测试集 = 分类数据集(测试样本, 分词器, 类别到编号, 配置.最大序列长度)
    校准集 = 分类数据集(校准样本, 分词器, 类别到编号, 配置.最大序列长度)
    return 训练集, 测试集, 校准集, 类别到编号
