# -*- coding: utf-8 -*-
# ============================================================
# 文件：真实数据.py
# 作用：从魔搭(modelscope)下载一个真实的【中文文本分类】数据集，
#       把它转换成和【合成数据.py】完全相同的数据集格式。
#       这样同一个实验流程既可以跑合成任务，也可以跑真实任务。
#
# ⚠️ 使用前提（不懂代码也能照着做）：
#   本文件默认是"半成品"——你只需要改下面【真实数据设置】这一小块，
#   把数据集 ID、文本字段名、标签字段名填对即可。
#   因为每个数据集的字段名都不一样，这里先给一个示例（阿里的 AFQMC 短文本分类）。
#
#   在 modelscope 上找一个文本分类数据集，通常要知道三件事：
#     数据集ID   ：例如 "iic/afqmc"（在数据集主页的地址里能看到）
#     文本字段名 ：例如 "sentence1"
#     标签字段名 ：例如 "label"
#
# 需要的条件：
#   - 需要联网（从魔搭下载数据集）。
#   - 需要安装 datasets 库。
#   - 如果你的数据是本地 CSV/JSONL 文件，可以不用魔搭，直接用
#     pandas / json 读进来（本文件也提供了这个入口）。
# ============================================================

# ---------- 导入标准库 ----------
from pathlib import Path

# ---------- 导入本项目 --------（保持包导入结构一致）
# 复用合成数据里的【分类数据集】类，保证格式统一
from 数据.合成数据 import 分类数据集

# ============================================================
# 【真实数据设置】—— 不懂代码的用户只改这一块
# ============================================================
数据集ID = "iic/afqmc"          # 魔搭上的数据集 ID（示例，按需替换）
文本字段名 = "sentence1"        # 数据里"待分类的句子"所在列名（示例）
标签字段名 = "label"            # 数据里"类别编号"所在列名（示例）
真实类别列表 = ["不相似", "相似"]  # 按数据集标签编号顺序写全类别名（示例）
本地数据文件 = None              # 如果从本地读，填文件路径（如 "数据/我的数据.csv"）
本地文本列 = "文本"              # 本地文件的文本列名
本地标签列 = "类别"              # 本地文件的标签列名
最大样本数 = 2000               # 最多用多少条（防止数据集太大跑不完）
测试比例 = 0.2                  # 划出 20% 做测试集
校准数量 = 60                   # 抽 60 条做校准集
# ============================================================


def 加载(配置, 分词器):
    """加载真实数据集并转换成训练/测试/校准三套数据集。

    参数：
      配置   ：配置项对象。
      分词器 ：transformers 分词器。
    返回：
      (训练集, 测试集, 校准集, 类别到编号)，与合成数据返回的结构完全一致。
    """
    # 1) 先取原始样本列表：[(句子, 类别), ...]
    原始样本 = 读取原始样本()

    # 2) 把样本按类别均衡、打乱，再划分成训练/测试/校准
    import random
    随机源 = random.Random(配置.随机种子)
    随机源.shuffle(原始样本)

    # 类别转编号
    类别到编号 = {类别: 序号 for 序号, 类别 in enumerate(真实类别列表)}

    # 用简单比例切分
    测试数量 = int(len(原始样本) * 测试比例)
    测试样本 = 原始样本[:测试数量]
    训练样本 = 原始样本[测试数量:]
    校准样本 = 训练样本[:校准数量]
    训练样本 = 训练样本[校准数量:]

    # 3) 转成统一的数据集对象
    训练集 = 分类数据集(训练样本, 分词器, 类别到编号, 配置.最大序列长度)
    测试集 = 分类数据集(测试样本, 分词器, 类别到编号, 配置.最大序列长度)
    校准集 = 分类数据集(校准样本, 分词器, 类别到编号, 配置.最大序列长度)
    return 训练集, 测试集, 校准集, 类别到编号


def 读取原始样本() -> list:
    """根据上面的设置，从魔搭或本地文件读取出 [(句子, 类别), ...]。

    注意：每个数据集的字段名不同，如果这里报错，多半是【文本字段名/标签字段名】填错了，
    请对照数据集主页的说明修改本文件顶部的设置。
    """
    # 分支一：优先读本地文件（最简单，不依赖网络）
    if 本地数据文件 is not None:
        return 读取本地文件()
    # 分支二：从魔搭下载
    return 读取魔搭数据集()


def 读取本地文件() -> list:
    """从本地 CSV 文件读取样本。"""
    import csv
    路径 = Path(本地数据文件)
    if not 路径.exists():
        raise FileNotFoundError(f"本地数据文件不存在：{路径}，请检查【本地数据文件】设置")
    样本 = []
    with open(路径, encoding="utf-8") as 文件句柄:
        读取器 = csv.DictReader(文件句柄)
        for 行 in 读取器:
            文本 = 行.get(本地文本列)
            标签 = 行.get(本地标签列)
            if 文本 is not None and 标签 is not None:
                样本.append((文本, str(标签)))
            if len(样本) >= 最大样本数:
                break
    return 样本


def 读取魔搭数据集() -> list:
    """从魔搭下载数据集并读取样本。

    实现说明：
      1) 用 datasets 库的 load_dataset 直接按魔搭的 ID 加载（modelscope 会自动走国内源）。
      2) 取出训练分片，按【文本字段名/标签字段名】取列。
      3) 把标签编号映射成类别名（用【真实类别列表】按序号对应）。
    """
    try:
        from datasets import load_dataset
    except ImportError as 异常:
        raise ImportError("未安装 datasets 库，请执行：pip install datasets") from 异常

    print(f"正在从魔搭下载数据集：{数据集ID} ...")
    # 加载数据集（第一次会下载，之后有缓存）
    数据集 = load_dataset(数据集ID, split="train")
    print(f"数据集下载完成，共 {len(数据集)} 条。")

    样本 = []
    for 单条 in 数据集:
        文本 = 单条.get(文本字段名)
        标签编号 = 单条.get(标签字段名)
        if 文本 is None or 标签编号 is None:
            continue  # 缺字段的跳过
        # 标签编号 → 类别名（注意要兼容字符串形式的编号）
        类别 = 真实类别列表[int(标签编号)] if int(标签编号) < len(真实类别列表) else f"未知{标签编号}"
        样本.append((str(文本), 类别))
        if len(样本) >= 最大样本数:
            break
    if not 样本:
        raise ValueError("没有读到任何有效样本，请检查【文本字段名/标签字段名】是否填写正确")
    return 样本
