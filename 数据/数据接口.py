# ============================================================
# 文件：数据接口.py
# 作用：数据的【统一入口】。上层代码（实验总控）只需要调用一个函数
#       就能拿到训练/测试/校准数据集，不用关心数据到底来自合成还是真实。
#       另外还提供一个小工具：验证类别词是否是"单个 token"。
#
# 需要的条件：
#   - 需要一个已经加载好的分词器。
#   - 其它依赖由 合成数据.py / 真实数据.py 各自负责。
# ============================================================


def 构建数据(配置, 分词器):
    """按配置的【数据来源】加载三套数据集。

    参数：
      配置   ：配置项对象。
      分词器 ：transformers 分词器。
    返回：
      (训练集, 测试集, 校准集, 类别到编号)
    """
    # 根据配置选择数据来源
    if 配置.数据来源 == "合成":
        # 合成任务：离线生成，不需要联网，默认推荐
        from 数据.合成数据 import 构建
        return 构建(配置, 分词器)
    elif 配置.数据来源 == "真实":
        # 真实任务：从魔搭下载（需要按 真实数据.py 顶部说明配置好字段）
        from 数据.真实数据 import 加载
        return 加载(配置, 分词器)
    else:
        # 配置填错时给出明确提示
        raise ValueError(f"配置里的【数据来源】只能是 '合成' 或 '真实'，当前是：{配置.数据来源}")


def 验证类别词是单个Token(分词器, 任务类别: tuple) -> dict:
    """验证每个类别词（如"甲"）切分后是否正好是一个 token。

    为什么要验证：我们的分类原理是"让模型预测下一个 token 是哪个类别词"。
    如果某个类别词被切成了两个 token，就没办法用"下一个 token"来判断类别了。

    参数：
      分词器   ：transformers 分词器。
      任务类别 ：例如 ("甲", "乙", "丙")。
    返回：
      类别到编号 字典，例如 {"甲": 0, "乙": 1, "丙": 2}。
    如果某个类别词不是单个 token，会直接抛出异常提示换词。
    """
    类别到编号 = {}
    for 序号, 类别词 in enumerate(任务类别):
        # 把类别词切分，看切成几个 token
        切分 = 分词器(类别词, add_special_tokens=False)["input_ids"]
        if len(切分) != 1:
            # 不是单个 token：报错，并告诉用户该换什么词
            raise ValueError(
                f"类别词「{类别词}」被切成了 {len(切分)} 个 token（{切分}），"
                f"无法用作分类标签。请到【配置.py】的【任务类别】里换一个能切成单个 token 的词。"
            )
        类别到编号[类别词] = 序号
    return 类别到编号
